<?php
/**
 * Starts Zinn® SEO: loads its core, the admin kit and the AI core, and hooks its start-up.
 *
 * Read by bootstrap.php through Boot::start(): at once, or — in a WP-CLI command that runs our
 * work — on WP-CLI's `after_wp_load`, with every already-fired action replayed (class-boot.php).
 *
 * ⛔ Explicit `require_once __DIR__ . '…'` lines for the core, never a path built at run time:
 * `scripts/wp-class-loadable.py` reads these lines statically. Feature MODULES are the one
 * exception, by design (architecture §1.2): each lives in `includes/modules/<id>/module.php` and
 * is found by Modules::discover(), so adding a module never edits a shared file.
 *
 * ⭐ Nothing here adds a hook that runs for a visitor unless a module asks for it: the front end
 * pays for the primer (one meta read for the queried objects) and nothing else.
 *
 * @package ZinnDigital\ZinnSEO
 */

declare( strict_types = 1 );

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

require_once __DIR__ . '/class-settings.php';
require_once __DIR__ . '/class-capabilities.php';
require_once __DIR__ . '/class-meta.php';
require_once __DIR__ . '/class-primer.php';
require_once __DIR__ . '/class-modules.php';
require_once __DIR__ . '/class-features.php';
require_once __DIR__ . '/class-jobs.php';
require_once __DIR__ . '/class-notrace.php';
require_once __DIR__ . '/class-counters.php';
require_once __DIR__ . '/class-setup.php';
require_once __DIR__ . '/class-transfer.php';
require_once __DIR__ . '/class-uninstall.php';
require_once __DIR__ . '/class-plugin.php';
require_once __DIR__ . '/class-rest.php';
require_once __DIR__ . '/class-api.php';
require_once __DIR__ . '/functions.php';
require_once __DIR__ . '/class-guide.php';
// A WP-CLI command that only reads plugins, themes, core or options (Modules::cli_lean()) loads
// neither the admin kit, the AI core nor the admin screens: measured 2026-10-13 (T1), every such
// command carried +18 MB and 361 of our files, past WP-CLI's 128 MB beside WooCommerce (PF-450).
$zinn_seo_cli_lean = defined( 'WP_CLI' ) && WP_CLI && \ZinnDigital\ZinnSEO\Modules::cli_lean();
if ( ! $zinn_seo_cli_lean ) {
	require_once __DIR__ . '/admin-kit/load.php';
	// The shared AI core (bring your own key; Settings → AI). GENERATED by wp/bin/build-ai-core.php.
	require_once __DIR__ . '/ai-core/load.php';
	require_once __DIR__ . '/admin/class-admin.php';
}
require_once __DIR__ . '/class-freemius-i18n.php';
// Generated by wp/bin/build-updater.php; the WordPress.org build removes this line and the file.
require_once __DIR__ . '/class-zinn-seo-updater.php';

if ( defined( 'WP_CLI' ) && WP_CLI ) {
	require_once __DIR__ . '/class-cli.php';
}

if ( ! $zinn_seo_cli_lean ) {
	\ZinnDigital\ZinnSEO\AdminKit\Kit::boot(
		array(
			'slug'           => 'zinn-seo',
			'name'           => 'Zinn® SEO',
			'version'        => ZINN_SEO_VERSION,
			'fs'             => 'zinn_seo_fs',
			'menu_slug'      => \ZinnDigital\ZinnSEO\Admin\Admin::SLUG,
			'rest_namespace' => \ZinnDigital\ZinnSEO\Plugin::REST_NS,
			'file'           => ZINN_SEO_FILE,
		)
	);
	\ZinnDigital\ZinnSEO\AiCore\Core::boot(
		array(
			'slug'    => 'zinn-seo',
			'name'    => 'Zinn® SEO',
			'pro'     => static function (): bool {
				return \ZinnDigital\ZinnSEO\Plugin::is_pro();
			},
			// Zinn® credits through this site's connection, for every plugin carrying the AI core
			// (zs-197). The door's code loads only when something asks for AI.
			'credits' => array(
				'complete' => static function ( array $requests, string $purpose ): array {
					require_once __DIR__ . '/modules/ai/class-door.php';
					return \ZinnDigital\ZinnSEO\Ai\Door::complete( $requests, $purpose );
				},
				'state'    => static function (): array {
					require_once __DIR__ . '/modules/ai/class-door.php';
					return \ZinnDigital\ZinnSEO\Ai\Door::state();
				},
			),
			// The owner's choice in Zinn® SEO → AI: own key, Zinn® credits, or automatic.
			'choose'  => static function ( string $task ): ?array {
				require_once __DIR__ . '/modules/ai/class-door.php';
				return \ZinnDigital\ZinnSEO\Ai\Door::choose( $task );
			},
		)
	);
}
\ZinnDigital\ZinnSEO\Plugin::init();
// AI agents (MCP, stage P13): the routes of Settings → AI agents, and — while the switch is on —
// the write guard (dry run, approval, refusal) and the agents' log. The server itself is offered
// earlier, in bootstrap.php.
if ( ! $zinn_seo_cli_lean ) {
	\ZinnDigital\ZinnSEO\Mcp\Mcp::boot();
}
unset( $zinn_seo_cli_lean );
// The guide links travel with the admin app's data: a filter that runs in wp-admin only.
add_filter( 'zinn_seo_admin_data', array( '\ZinnDigital\ZinnSEO\Guide', 'admin_data' ) );
