<?php
/**
 * Loads Zinn® SEO and starts it.
 *
 * Only what must exist from the moment the plugin is read lives here: the class autoloader, the
 * start-up decision (Boot) and the public functions. The rest — the core, the admin kit, the AI
 * core and the start-up hooks — is in start.php, which Boot runs at once, or in a WP-CLI command
 * that runs our work, right after WordPress has loaded (stage PERF2: WP-CLI loads WordPress under
 * the 128 MB limit and lifts it only afterwards).
 *
 * @package ZinnDigital\ZinnSEO
 */

declare( strict_types = 1 );

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

require_once __DIR__ . '/class-autoload.php';
\ZinnDigital\ZinnSEO\Autoload::register();
require_once __DIR__ . '/class-modules.php';
require_once __DIR__ . '/class-boot.php';
// The public functions (zinn_seo(), zinn_seo_get_field() …) exist from the moment the plugin is
// read: Tranzly and Page Builder Sandwich look for them on `plugins_loaded`, whenever we start.
require_once __DIR__ . '/functions.php';

// ⭐ Anything that must run WHILE WordPress loads even when the start is deferred (Boot) goes
// here, before Boot::start().
//
// AI agents (MCP, stage P13): the WordPress MCP adapter is chosen at `plugins_loaded` priority 5,
// so the server is OFFERED here, while WordPress loads. With the switch off (the default) this is
// one file and one option read; with it on, the shared MCP kit (GENERATED by
// wp/bin/build-mcp-kit.php) and the server's configuration. The module's routes, its write guard
// and its log start with the rest of the plugin (start.php → Mcp::boot()).
// The site's own address keeps https when WordPress cannot tell from the request (WP-CLI, a
// scheduled task, a proxy): the licensing service records it, and its e-mails link to it.
require_once __DIR__ . '/class-site-address.php';
\ZinnDigital\ZinnSEO\Site_Address::register();

require_once __DIR__ . '/modules/mcp/class-mcp.php';
\ZinnDigital\ZinnSEO\Mcp\Mcp::offer();

// Who registers each content type (Search appearance › Content types, Q277): noted while
// WordPress loads — a deferred start comes after every type is registered. wp-admin, the REST API
// and WP-CLI only; a visitor's page adds nothing.
\ZinnDigital\ZinnSEO\Templates\Content_Types::capture_early();
// Start at once, or after WordPress has loaded in a WP-CLI command that runs our work (Boot).
\ZinnDigital\ZinnSEO\Boot::start(
	static function (): void {
		require_once __DIR__ . '/start.php';
	}
);

register_activation_hook( ZINN_SEO_FILE, array( '\ZinnDigital\ZinnSEO\Plugin', 'activate' ) );
register_deactivation_hook( ZINN_SEO_FILE, array( '\ZinnDigital\ZinnSEO\Plugin', 'deactivate' ) );

if ( ! function_exists( 'zinn_seo_uninstall' ) ) {
	/**
	 * Delete everything this plugin stored, unless the owner chose to keep it. Called by the
	 * licensing SDK's `after_uninstall` action (it refuses a root uninstall.php).
	 *
	 * @return void
	 */
	function zinn_seo_uninstall(): void {
		\ZinnDigital\ZinnSEO\Uninstall::run();
	}
}
