/**
 * `/llms.txt` tells AI assistants what the site is and which pages matter, with each page's
 * description; `/llms-full.txt` carries those pages' text. Both are written once to a file and
 * sent from it until something they list changes (a save of a listed type, a setting).
 *
 * The pages: the ones the owner picked, else the front page and the top-level pages; then the
 * newest pages of each chosen content type (`llms_per_type` of each, up to 5,000 — a site moving
 * from Rank Math keeps the 1,000 a type it listed there, and the pages it listed when "Pages" was
 * one of its types; a page already among the key pages is listed once). Pages asking not to be
 * indexed are never listed.
 *
 * With Tranzly and more than one language, every language has its own file at Tranzly's address
 * for it (`/de/llms.txt` in folders mode, `/llms.txt?lang=de` in query mode), listing that
 * language's translations with their own titles and descriptions, and the root file links each.
 *
 * ⛔ No "generated by" credit line (WordPress.org guideline 10: no credit on the public site
 * without the owner's consent) — which is also what no-trace mode needs.
 */
final class Llms {

	/** Cache folder under uploads. */
	public const DIR = 'zd-private/llms';

	/**
	 * Settings.
	 *
	 * @return array<string, array<string, mixed>>
	 */
	public static function settings(): array {
		return require __DIR__ . '/settings.php';
	}

	/**
	 * Hooks.
	 *
	 * @param string $context Request context.
	 * @return void
	 */
	public static function boot( string $context ): void {
		foreach ( array( 'save_post', 'deleted_post', 'trashed_post' ) as $hook ) {
			add_action( $hook, array( self::class, 'on_post' ), 10, 1 );
		}
		add_action( 'zinn_seo_settings_saved', array( self::class, 'forget' ) );
		add_action( 'zinn_seo_field_saved', array( self::class, 'forget' ) );
		add_action( 'update_option_blogname', array( self::class, 'forget' ) );
		add_action( 'update_option_blogdescription', array( self::class, 'forget' ) );
		if ( 'front' === $context && Head::should_print() ) {
			// After `init`: content types, permalinks and translations are ready.
			add_action( 'wp_loaded', array( self::class, 'maybe_serve' ) );
		}
	}

	// ── Serving ───────────────────────────────────────────────────────────────────────────────

	/**
	 * Which file a request is: [language ('' default), full], or null.
	 *
	 * @return array{0: string, 1: bool}|null
	 */
	public static function route(): ?array {
		if ( ! isset( $_SERVER['REQUEST_URI'] ) ) {
			return null;
		}
		$uri  = esc_url_raw( wp_unslash( (string) $_SERVER['REQUEST_URI'] ) );
		$path = (string) wp_parse_url( $uri, PHP_URL_PATH );
		if ( false === strpos( $path, 'llms' ) ) {
			return null;
		}
		$rel  = \ZinnDigital\ZinnSEO\Sitemaps\Sitemaps::relative( $path, (string) wp_parse_url( home_url( '/' ), PHP_URL_PATH ) );
		$full = null;
		if ( 'llms.txt' === $rel ) {
			$full = false;
		} elseif ( 'llms-full.txt' === $rel ) {
			$full = true;
		}
		$languages = self::languages();
		if ( null !== $full ) {
			// Query mode (`?lang=de`), or a language folder already removed from the address.
			$current = function_exists( 'tranzly_current_language' ) && count( $languages ) > 1 ? (string) tranzly_current_language() : '';
			return array( isset( $languages[ $current ] ) && self::default_language() !== $current ? $current : '', $full );
		}
		foreach ( array_keys( $languages ) as $code ) {
			if ( self::default_language() === $code ) {
				continue;
			}
			foreach ( array( false, true ) as $is_full ) {
				$own = (string) wp_parse_url( self::url( $code, $is_full ), PHP_URL_PATH );
				if ( $own === $path ) {
					return array( (string) $code, $is_full );
				}
			}
		}

		return null;
	}

	/**
	 * Answer an llms.txt request, if this is one.
	 *
	 * @return void
	 */
	public static function maybe_serve(): void {
		$route = self::route();
		if ( null === $route ) {
			return;
		}
		list( $lang, $full ) = $route;
		if ( $full && ! (bool) Settings::get( 'llms_full', true ) ) {
			return;
		}
		/**
		 * Fires when llms.txt or llms-full.txt was requested (the AI-crawler log counts bots).
		 *
		 * @param string $lang Language ('' for the default).
		 * @param bool   $full llms-full.txt.
		 */
		do_action( 'zinn_seo_served_llms', $lang, $full );
		$body = self::text( $lang, $full );
		status_header( 200 );
		header( 'Content-Type: text/plain; charset=UTF-8' );
		header( 'X-Robots-Tag: noindex' );
		header( 'Cache-Control: public, max-age=3600' );
		header( 'Content-Length: ' . strlen( $body ) );
		if ( ! isset( $_SERVER['REQUEST_METHOD'] ) || 'HEAD' !== strtoupper( sanitize_text_field( wp_unslash( (string) $_SERVER['REQUEST_METHOD'] ) ) ) ) {
			echo $body; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- plain text (text/plain), built from escaped Markdown.
		}
		exit;
	}

	/**
	 * The file's text: from the cache, or built and cached.
	 *
	 * @param string $lang Language ('' default).
	 * @param bool   $full llms-full.txt.
	 * @return string
	 */
	public static function text( string $lang, bool $full ): string {
		$file = self::cache_path( $lang, $full );
		if ( '' !== $file && is_readable( $file ) ) {
			return (string) file_get_contents( $file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- our own cached file.
		}
		$text = self::build( $lang, $full );
		if ( '' !== $file ) {
			file_put_contents( $file . '.tmp', $text ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents -- our own cache file.
			rename( $file . '.tmp', $file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.rename_rename -- an atomic swap of our own file.
		}

		return $text;
	}

	/**
	 * A cache file's path ('' when uploads cannot be written).
	 *
	 * @param string $lang Language.
	 * @param bool   $full Full.
	 * @return string
	 */
	private static function cache_path( string $lang, bool $full ): string {
		$uploads = wp_get_upload_dir();
		$dir     = trailingslashit( (string) $uploads['basedir'] ) . self::DIR;
		if ( ! is_dir( $dir ) && ! wp_mkdir_p( $dir ) ) {
			return '';
		}
		$name = '' === $lang ? 'default' : strtolower( (string) preg_replace( '/[^a-z0-9]+/i', '-', $lang ) );

		return $dir . '/' . $name . ( $full ? '-full' : '' ) . '.txt';
	}

	/**
	 * Drop every cached file (something they list changed).
	 *
	 * @return void
	 */
	public static function forget(): void {
		$uploads = wp_get_upload_dir();
		$dir     = trailingslashit( (string) $uploads['basedir'] ) . self::DIR;
		if ( ! is_dir( $dir ) ) {
			return;
		}
		foreach ( (array) scandir( $dir ) as $file ) {
			if ( is_string( $file ) && 1 === preg_match( '/^[a-z0-9-]+\.txt$/', $file ) ) {
				wp_delete_file( $dir . '/' . $file );
			}
		}
	}

	/**
	 * A post was saved or removed: forget the files when its type is one they list.
	 *
	 * @param int $post_id Post ID.
	 * @return void
	 */
	public static function on_post( $post_id ): void {
		$type = get_post_type( (int) $post_id );
		if ( is_string( $type ) && in_array( $type, array_merge( array( 'page' ), self::types() ), true ) ) {
			self::forget();
		}
	}

	// ── Content ──────────────────────────────────────────────────────────────────────────────

	/**
	 * The content types whose newest pages are listed.
	 *
	 * @return array<int, string>
	 */
	public static function types(): array {
		$chosen = (array) Settings::get( 'llms_types', array() );
		if ( array() === $chosen ) {
			$chosen = array( 'post' );
			if ( post_type_exists( 'product' ) ) {
				$chosen[] = 'product';
			}
		}

		return array_values(
			array_filter(
				array_map( 'strval', $chosen ),
				static fn( string $t ): bool => 'attachment' !== $t && is_post_type_viewable( $t )
			)
		);
	}

	/**
	 * The listed pages, as sections of posts.
	 *
	 * @return array<int, array{title: string, posts: array<int, \WP_Post>}>
	 */
	public static function sections(): array {
		global $wpdb;
		$per      = max( 1, min( 5000, (int) Settings::get( 'llms_per_type', 25 ) ) );
		$sections = array();
		$only     = self::default_language_sql();
		$picked   = array_values( array_filter( array_map( 'intval', preg_split( '/[\s,]+/', (string) Settings::get( 'llms_pages', '' ) ) ) ) );
		if ( array() !== $picked ) {
			_prime_post_caches( $picked, false, true );
			$key = array();
			foreach ( $picked as $id ) {
				$post = get_post( $id );
				if ( $post instanceof \WP_Post ) {
					$key[] = $post;
				}
			}
		} else {
			$key   = array();
			$front = (int) get_option( 'page_on_front' );
			if ( 'page' === get_option( 'show_on_front' ) && $front > 0 ) {
				$post = get_post( $front );
				if ( $post instanceof \WP_Post ) {
					$key[] = $post;
				}
			}
			$ids = $wpdb->get_col( $wpdb->prepare( "SELECT ID FROM {$wpdb->posts} WHERE post_type = 'page' AND post_status = 'publish' AND post_password = '' AND post_parent = 0 AND ID <> %d{$only} ORDER BY menu_order ASC, post_title ASC LIMIT %d", $front, $per ) ); // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared, PluginCheck.Security.DirectDB.UnescapedDBParameter -- $only is built by default_language_sql() from a checked table name and an escaped language code.
			_prime_post_caches( array_map( 'intval', (array) $ids ), false, true );
			foreach ( (array) $ids as $id ) {
				$post = get_post( (int) $id );
				if ( $post instanceof \WP_Post ) {
					$key[] = $post;
				}
			}
		}
		$sections[] = array(
			'title' => __( 'Key pages', 'zinn-seo' ),
			'posts' => $key,
		);
		foreach ( self::types() as $type ) {
			$object = get_post_type_object( $type );
			if ( ! $object instanceof \WP_Post_Type ) {
				continue;
			}
			$ids = $wpdb->get_col( $wpdb->prepare( "SELECT ID FROM {$wpdb->posts} WHERE post_type = %s AND post_status = 'publish' AND post_password = ''{$only} ORDER BY post_date DESC, ID DESC LIMIT %d", $type, $per ) ); // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared, PluginCheck.Security.DirectDB.UnescapedDBParameter -- $only is built by default_language_sql() from a checked table name and an escaped language code.
			$ids = array_map( 'intval', (array) $ids );
			_prime_post_caches( $ids, false, true );
			$posts = array();
			foreach ( $ids as $id ) {
				$post = get_post( $id );
				if ( $post instanceof \WP_Post ) {
					$posts[] = $post;
				}
			}
			$sections[] = array(
				'title' => (string) $object->labels->name,
				'posts' => $posts,
			);
		}

		// The terms of the chosen taxonomies (a site moving from Rank Math keeps the ones it listed
		// there): by name, those with content, never one asking not to be indexed.
		foreach ( array_map( 'strval', (array) Settings::get( 'llms_taxonomies', array() ) ) as $tax ) {
			$object = get_taxonomy( $tax );
			if ( ! $object instanceof \WP_Taxonomy || ! $object->public ) {
				continue;
			}
			$terms = get_terms(
				array(
					'taxonomy'   => $tax,
					'hide_empty' => true,
					'number'     => $per,
				)
			);
			$links = array();
			foreach ( is_array( $terms ) ? $terms : array() as $term ) {
				if ( ! $term instanceof \WP_Term || isset( Resolver::robots( Context::for_term( $term ) )['noindex'] ) ) {
					continue;
				}
				$url = get_term_link( $term );
				if ( is_string( $url ) ) {
					$links[] = array(
						'title' => $term->name,
						'url'   => $url,
						'desc'  => '',
					);
				}
			}
			$sections[] = array(
				'title' => (string) $object->labels->name,
				'posts' => array(),
				'links' => $links,
			);
		}

		/**
		 * Filters the pages llms.txt lists, as sections (`title`, `posts`, optional `links`).
		 *
		 * @param array<int, array{title: string, posts: array<int, \WP_Post>}> $sections Sections.
		 */
		return (array) apply_filters( 'zinn_seo_llms_sections', $sections );
	}

	/**
	 * Build a file.
	 *
	 * @param string $lang Language ('' default).
	 * @param bool   $full llms-full.txt.
	 * @return string
	 */
	public static function build( string $lang, bool $full ): string {
		$switched = false;
		if ( '' !== $lang && function_exists( 'switch_to_locale' ) ) {
			$switched = switch_to_locale( $lang );
		}
		$sections = array();
		$seen     = array();
		$text     = '';
		// The sitemap index first: everything else the site has, for a reader that wants it all.
		if ( ! $full && \ZinnDigital\ZinnSEO\Modules::enabled( 'sitemaps' ) && class_exists( 'ZinnDigital\\ZinnSEO\\Sitemaps\\Sitemaps' ) && \ZinnDigital\ZinnSEO\Sitemaps\Sitemaps::active() ) {
			$sections[] = array(
				'title' => __( 'Sitemaps', 'zinn-seo' ),
				'items' => array(
					array(
						'title' => __( 'XML Sitemap', 'zinn-seo' ),
						'url'   => \ZinnDigital\ZinnSEO\Sitemaps\Sitemaps::url(),
						'desc'  => '',
					),
				),
			);
		}
		foreach ( self::sections() as $section ) {
			$items = array();
			foreach ( (array) $section['posts'] as $post ) {
				$post = self::in_language( $post, $lang );
				if ( null === $post || isset( $seen[ $post->ID ] ) ) {
					continue;
				}
				$c = Context::for_post( $post );
				if ( isset( Resolver::robots( $c )['noindex'] ) ) {
					continue;
				}
				$seen[ $post->ID ] = true;
				$url               = (string) get_permalink( $post );
				// The page's own llms.txt summary when one was written (Pro AI, zs-063, kept on
				// each language's page), else its meta description.
				$summary = isset( Meta::fields()['llms_summary'] ) ? trim( (string) Meta::get_post( (int) $post->ID, 'llms_summary' ) ) : '';
				$item    = array(
					'title' => get_the_title( $post ),
					'url'   => $url,
					'desc'  => '' !== $summary ? $summary : Resolver::description( $c ),
				);

				/**
				 * Filters one page's line in llms.txt (the Pro Markdown version links its `.md`).
				 *
				 * @param array{title: string, url: string, desc: string} $item Line.
				 * @param \WP_Post                                        $post Page.
				 */
				$items[] = (array) apply_filters( 'zinn_seo_llms_item', $item, $post );
				if ( $full ) {
					$text .= Llms_Text::full_entry( get_the_title( $post ), $url, self::markdown_of( $post ) );
				}
			}
			// Links that are not pages (the site graph of the schema module, zs-038).
			foreach ( (array) ( $section['links'] ?? array() ) as $link ) {
				if ( is_array( $link ) && ! empty( $link['url'] ) ) {
					$items[] = array(
						'title' => (string) ( $link['title'] ?? '' ),
						'url'   => (string) $link['url'],
						'desc'  => (string) ( $link['desc'] ?? '' ),
					);
				}
			}
			$sections[] = array(
				'title' => (string) $section['title'],
				'items' => $items,
			);
		}
		$languages = self::languages();
		if ( '' === $lang && count( $languages ) > 1 && ! $full ) {
			$items = array();
			foreach ( $languages as $code => $name ) {
				if ( self::default_language() !== $code ) {
					$items[] = array(
						'title' => $name,
						'url'   => self::url( (string) $code, false ),
						'desc'  => '',
					);
				}
			}
			$sections[] = array(
				'title' => __( 'Other languages', 'zinn-seo' ),
				'items' => $items,
			);
		}
		$site = array(
			'name'    => '' !== (string) Settings::get( 'identity_name', '' ) ? (string) Settings::get( 'identity_name', '' ) : self::in_words_of( $lang, 'blogname', (string) get_bloginfo( 'name' ) ),
			'summary' => '' !== (string) Settings::get( 'llms_summary', '' ) ? self::in_words_of( $lang, 'llms_summary' ) : self::in_words_of( $lang, 'blogdescription', (string) get_bloginfo( 'description' ) ),
			'details' => self::in_words_of( $lang, 'llms_details' ),
		);
		$out  = $full ? '# ' . Llms_Text::line( $site['name'] ) . "\n\n" . ( '' !== trim( $site['summary'] ) ? '> ' . Llms_Text::line( $site['summary'] ) . "\n\n" : '' ) . $text : Llms_Text::index( $site, $sections );
		if ( $switched ) {
			restore_previous_locale();
		}

		return $out;
	}

	/**
	 * A site-wide text of the file in the file's language: its translation when a translation
	 * plugin keeps one (Tranzly answers `zinn_seo_site_text`), else as the owner wrote it.
	 *
	 * @param string      $lang Language ('' default).
	 * @param string      $key  Setting, or `blogname` / `blogdescription` for WordPress's own.
	 * @param string|null $text The text, when it is not one of this plugin's settings.
	 * @return string
	 */
	private static function in_words_of( string $lang, string $key, ?string $text = null ): string {
		$text = $text ?? (string) Settings::get( $key, '' );
		if ( '' === $lang || '' === trim( $text ) ) {
			return $text;
		}
		$given = apply_filters( 'zinn_seo_site_text', $text, $key, $lang ); // phpcs:ignore WordPress.NamingConventions.ValidHookName -- documented in Family::site_text().

		return is_string( $given ) && '' !== trim( $given ) ? $given : $text;
	}

	/**
	 * A page's text as Markdown (its content rendered as a visitor would get it).
	 *
	 * @param \WP_Post $post Post.
	 * @return string
	 */
	public static function markdown_of( \WP_Post $post ): string {
		// Q335: a page whose rendering ended an earlier request (a shortcode that redirects and
		// exits) is left out instead of cutting llms-full.txt short again; while this one
		// renders, the guard knows which page to blame if it does.
		$render = class_exists( '\\ZinnDigital\\ZinnSEO\\Analysis\\Render' );
		if ( $render && null !== \ZinnDigital\ZinnSEO\Analysis\Render::refused( $post ) ) {
			return '';
		}
		$previous        = $GLOBALS['post'] ?? null;
		$GLOBALS['post'] = $post; // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited -- blocks and shortcodes read the global post while the content renders; restored below.
		setup_postdata( $post );
		// A page's content may try to send the visitor elsewhere (a members-only shortcode asking
		// for a login) or print on its own: neither may happen while llms-full.txt is written
		// (zinnhub.com, 2026-10-14: one such page turned llms-full.txt into a redirect to the
		// login page). Its redirect is refused and anything it prints is dropped.
		$no_redirect = static fn() => false;
		add_filter( 'wp_redirect', $no_redirect, PHP_INT_MAX );
		if ( $render ) {
			\ZinnDigital\ZinnSEO\Analysis\Render::begin( $post );
		}
		ob_start();
		try {
			$html = (string) apply_filters( 'the_content', (string) $post->post_content ); // phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound -- WordPress core's own filter.
		} catch ( \Throwable $e ) {
			$html = '';
		} finally {
			ob_end_clean();
			if ( $render ) {
				\ZinnDigital\ZinnSEO\Analysis\Render::end();
			}
			remove_filter( 'wp_redirect', $no_redirect, PHP_INT_MAX );
		}
		$GLOBALS['post'] = $previous; // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited -- restoring what was there.
		if ( $previous instanceof \WP_Post ) {
			setup_postdata( $previous );
		}

		return Markdown::from_html( $html, home_url() );
	}

	/**
	 * The page in a language: itself for the default language, else its published translation.
	 *
	 * @param \WP_Post $post Page.
	 * @param string   $lang Language ('' default).
	 * @return \WP_Post|null
	 */
	private static function in_language( \WP_Post $post, string $lang ): ?\WP_Post {
		if ( ! function_exists( 'tranzly_get_translation' ) ) {
			return '' === $lang ? $post : null;
		}
		if ( '' === $lang ) {
			// The root file is the default language's: a page written in another language (one the
			// owner picked by hand, or one a filter added) belongs to that language's own file.
			$default = self::default_language();

			return '' === $default || count( self::languages() ) < 2 || tranzly_get_translation( (int) $post->ID, $default ) === (int) $post->ID ? $post : null;
		}
		$id = tranzly_get_translation( (int) $post->ID, $lang );
		if ( null === $id ) {
			return null;
		}
		$translated = get_post( (int) $id );

		return $translated instanceof \WP_Post && 'publish' === $translated->post_status && '' === $translated->post_password ? $translated : null;
	}

	// ── Languages ────────────────────────────────────────────────────────────────────────────

	/**
	 * The SQL that keeps a list of pages to the DEFAULT language ('' on a site with one language).
	 *
	 * ⛔ WHY. With Tranzly a translation is a page of its own, so "the top-level pages" and "the
	 * newest posts" are those of every language at once: live 2026-10-11 the root llms.txt of
	 * demo.zinnseo.com listed 68 addresses under /de/, /ar/, /es/ and /fr/ besides its "Other
	 * languages" section. The root file lists the default language only; each other language has
	 * its own file, built from these same pages through their translations. A page Tranzly holds
	 * no language for is in the default language.
	 *
	 * @return string
	 */
	private static function default_language_sql(): string {
		global $wpdb;
		$default = self::default_language();
		if ( '' === $default || count( self::languages() ) < 2 || ! class_exists( \ZinnDigital\ZinnSEO\Sitemaps\Builder::class ) ) {
			return '';
		}
		$table = \ZinnDigital\ZinnSEO\Sitemaps\Builder::relations_table();
		if ( '' === $table ) {
			return '';
		}

		return $wpdb->prepare( " AND NOT EXISTS ( SELECT 1 FROM {$table} zr WHERE zr.object_type = 'post' AND zr.object_id = {$wpdb->posts}.ID AND zr.lang <> %s )", $default ); // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared -- the table name is checked against /^[A-Za-z0-9_]+$/ by Builder::relations_table().
	}

	/**
	 * The site's languages through Tranzly: code => name (empty without Tranzly).
	 *
	 * @return array<string, string>
	 */
	public static function languages(): array {
		if ( ! function_exists( 'tranzly_languages' ) ) {
			return array();
		}
		$out = array();
		foreach ( (array) tranzly_languages() as $language ) {
			if ( isset( $language['code'] ) ) {
				$out[ (string) $language['code'] ] = (string) ( $language['name'] ?? $language['code'] );
			}
		}

		return $out;
	}

	/**
	 * The default language.
	 *
	 * @return string
	 */
	public static function default_language(): string {
		return function_exists( 'tranzly_default_language' ) ? (string) tranzly_default_language() : '';
	}

	/**
	 * A file's public address.
	 *
	 * @param string $lang Language ('' default).
	 * @param bool   $full llms-full.txt.
	 * @return string
	 */
	public static function url( string $lang, bool $full ): string {
		$url = home_url( $full ? '/llms-full.txt' : '/llms.txt' );
		if ( '' !== $lang && self::default_language() !== $lang && function_exists( 'tranzly_language_url' ) ) {
			$url = (string) tranzly_language_url( $lang, $url );
		}

		return $url;
	}
